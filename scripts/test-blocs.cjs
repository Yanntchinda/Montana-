'use strict';
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('index.html', 'utf8');
const start = html.indexOf('const ETAGES_BASE =');
const end = html.indexOf('/* ============================================================\n   TABLEAU DE BORD', start);
const context = { $: () => null, sauver() {}, updateDashboard() {}, toast() {}, window: { confirm: () => true } };
vm.createContext(context);
vm.runInContext(html.slice(start, end), context);
for (const id of ['fondation', 'rdc', 'etage1', 'toiture', 'autres']) assert.equal(context.etageOuvert(id), false);
context.basculerBloc('rdc');
assert.equal(context.etageOuvert('rdc'), true);
assert.equal(context.etageOuvert('etage1'), false);
context.basculerBloc('rdc');
assert.equal(context.etageOuvert('rdc'), false);
context.ajouterEtage();
assert.equal(context.etageOuvert('etage2'), false);
const aller = html.slice(html.indexOf('function aller('), html.indexOf("window.addEventListener('hashchange'"));
assert.doesNotMatch(aller, /etagesOuverts\[[^\]]+\]\s*=\s*true|basculerBloc/);
assert.match(html, /etagesOuverts = \{\};/);
console.log('✓ blocs fermés au démarrage et ouverture uniquement au clic');
