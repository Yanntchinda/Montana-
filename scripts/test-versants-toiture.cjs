'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8');
const source = html.slice(html.indexOf('const TOITURE_GROUPES ='), html.indexOf('function calculToitureActuel()'));
const ctx = {}; vm.createContext(ctx); vm.runInContext(source, ctx);
const v = [{L:'10',largeur:'4',pente:'0'},{L:'8',largeur:'3',pente:'0'},{L:'6',largeur:'2',pente:'0'}];
const inputs = {'tole-largeur':1,'tole-rec-lat':0,'tole-longueur':5,'tole-rec-bout':0,'tole-pertes':0,'panne-entraxe':2,'panne-piece':4,'panne-pertes':0,'ferme-piece':4,'ferme-pertes':0};
let r = ctx.calculToitureLibre(inputs,'rangees',v,3,4,10);
assert.equal(r.surface,76); assert.equal(r.toles,24); assert.equal(r.piecesFermes,10); assert.equal(r.piecesPannes,17); assert.equal(r.erreurs.length,0);
assert.equal(ctx.calculToitureLibre(inputs,'surface',v,3,4,10).toles,16);
assert.equal(ctx.calculToitureLibre(inputs,'rangees',v,2,4,10).surface,64);
assert.equal(ctx.calculToitureLibre(inputs,'rangees',v,21,4,10).baseValide,false);
assert.equal(ctx.calculToitureLibre(inputs,'rangees',[{L:10,largeur:4,pente:''}],1,4,10).baseValide,false);
assert.ok(ctx.calculToitureLibre(inputs,'rangees',v,3,1.5,10).erreurs.includes('fermes'));
const incline=ctx.calculToitureLibre({},'rangees',[{L:10,largeur:4,pente:100}],1,'','');
assert.ok(Math.abs(incline.surface-40*Math.sqrt(2)) < 1e-10);
assert.match(html, /'toi-versants'/); assert.match(html, /afficherVersants\(\);\s*syncMainDoeuvreDevis/);
console.log('✓ versants indépendants : géométrie, matériaux, limites et validation');
