'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8');
const source = html.slice(html.indexOf('function afficherAccueilProjet('), html.indexOf('function charger() {'));
const storage = () => { const m = new Map(); return { getItem: k => m.has(k) ? m.get(k) : null, setItem: (k, v) => m.set(k, String(v)), removeItem: k => m.delete(k) }; };
const localStorage = storage(), sessionStorage = storage();
let confirmed = false, reloads = 0, errors = [];
const nodes = { 'login-entreprise': {value:'Entreprise'}, 'login-projet': {value:'Maison'} };
const ctx = { localStorage, sessionStorage, CLE:'project', CLE_RECENTS:'recents', MAX_RECENTS:10, projetId:'ancien', $: id => nodes[id], window:{confirm:()=>confirmed}, alert: msg=>errors.push(msg), location:{hash:'',reload:()=>reloads++}, clearTimeout(){}, saveTimer:null, reinitialisationEnCours:false, projetOuvert:false, URL:{}, Blob, document:{}, requestAnimationFrame: cb => setTimeout(cb, 0), setTimeout };
vm.createContext(ctx); vm.runInContext(source, ctx);
(async () => {
  const old = JSON.stringify({v:2, projetId:'ancien', champs:{'dv-projet':'Ancien'}});
  localStorage.setItem('project', old);
  await ctx.nouveauProjet();
  assert.equal(localStorage.getItem('project'), old); assert.equal(reloads, 0);
  const input = text => ({ value:'x', files:[{ text:async()=>text }] });
  await ctx.importerProjet(input('{bad')); assert.equal(localStorage.getItem('project'), old); assert.equal(errors.length,1);
  const data={v:2,champs:{},murs:[],poteaux:[],amorces:[],poutres:[],chenages:[],mainsOeuvre:[],dalles:[],corps:[],semelles:[],longrines:[],devis:[]};
  await ctx.importerProjet(input(JSON.stringify(data))); assert.equal(localStorage.getItem('project'), old);
  confirmed=true; await ctx.importerProjet(input(JSON.stringify(data)));
  assert.deepEqual(JSON.parse(localStorage.getItem('project')),data);
  assert.equal(JSON.parse(sessionStorage.getItem('go-import-sauvegarde')).ancien,old);
  assert.equal(JSON.parse(sessionStorage.getItem('go-ouverture-projet')).type,'import');
  assert.equal(JSON.parse(localStorage.getItem('recents'))[0].projetId, 'ancien');
  ctx.terminerChargement();
  localStorage.setItem('project',old); await ctx.nouveauProjet();
  assert.equal(localStorage.getItem('project'),null);
  assert.deepEqual(JSON.parse(sessionStorage.getItem('go-ouverture-projet')),{type:'nouveau',entreprise:'Entreprise',projet:'Maison'});
  const login = html.slice(html.indexOf('<div class="login-screen" id="login-screen">'), html.indexOf('<div class="app">'));
  assert.doesNotMatch(login, /nouveauProjet|importerProjet|exporterProjet|accederApp/);
  const accueil = html.slice(html.indexOf('<section class="panel active" id="panel-dashboard">'), html.indexOf('<!-- ============ ONGLET : CRÉPISSAGE'));
  assert.match(accueil, /Projets récents/);
  assert.match(html, /body\.sans-projet \.sidebar/);
  assert.match(html, /id="panel-projet"/);
  assert.match(html, /aller\('projet', \{ silent: true \}\)/);
  assert.match(html, /class="barre-outils-projet no-print"/);
  assert.match(html, /role="progressbar"/);
  assert.match(accueil, /continuerDepuisAccueil/);
  assert.match(accueil, /choisirFichierProjet/);
  assert.match(accueil, /exporterDepuisAccueil/);
  assert.doesNotMatch(accueil, /dash-beton|dash-repart|dash-modules|dash-mat/);
  for (const label of ['Nouveau projet', 'Continuer le projet enregistré', 'Ouvrir un fichier projet', 'Exporter le projet enregistré']) assert.ok(accueil.includes(label));
  assert.doesNotMatch(accueil, /dash-construction-slider|login-slide/);
  assert.match(login, /login-slides/);
  assert.match(html, /@keyframes loginSlide/);
  assert.match(html,/if \(reinitialisationEnCours \|\| !projetOuvert\) return/);
  console.log('✓ accueil : annulation, import, export de sécurité et nouveau projet');
})().catch(e => { console.error(e); process.exitCode=1; });
