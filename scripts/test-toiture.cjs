'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('index.html', 'utf8');
const source = html.slice(html.indexOf('const TOITURE_GROUPES ='), html.indexOf('function calculToitureActuel()'));
const ctx = {}; vm.createContext(ctx); vm.runInContext(source, ctx);
const input = {L:10,l:8,d:0.5,dp:0.3,pente:30,'tole-largeur':0.9,'tole-rec-lat':0.1,'tole-longueur':3,'tole-rec-bout':0.2,'tole-pertes':10,'ferme-entraxe':2.5,'ferme-debord':0,'ferme-contrefiche':2,'ferme-piece':4,'ferme-pertes':10,'panne-entraxe':1,'panne-piece':4,'panne-pertes':10};
let r = ctx.calculToiture(input,'rangees');
const a = r.affichage, lr = 4.5 * Math.sqrt(1.09);
assert.ok(Math.abs(a.rampant - lr) < 1e-10); assert.ok(Math.abs(a.surface - 2 * lr * 10.6) < 1e-10);
assert.equal(a.hauteur,1.2); assert.equal(a.rangees,14); assert.equal(a.tolesRangee,2); assert.equal(r.toles,56);
assert.equal(a.toleSurface,49); assert.equal(a.fermes,5); assert.equal(r.piecesFermes,33); assert.equal(a.panneVersant,6); assert.equal(r.piecesPannes,35);
assert.equal(ctx.calculToiture(input,'surface').toles,49);
assert.equal(ctx.calculToiture({...input,'tole-longueur':lr,'tole-rec-bout':0.2},'rangees').affichage.tolesRangee,1);
assert.ok(ctx.calculToiture({...input,'tole-rec-lat':0.9}).erreurs.includes('toles'));
assert.ok(ctx.calculToiture({...input,'panne-entraxe':0}).erreurs.includes('pannes'));
assert.equal(ctx.calculToiture({L:10,l:8,d:0,dp:0,pente:0}).baseValide,true);
assert.equal(ctx.calculToiture({L:10,l:8,d:'',dp:0,pente:0}).baseValide,false);
assert.ok(ctx.calculToiture({L:10,l:8,d:0,dp:0,pente:0,'ferme-piece':4}).erreurs.includes('fermes'));
assert.match(html, /modules: \['toiture'\]/); assert.match(html, /toiture:piecesFermes/);
console.log('✓ toiture : géométrie, tôles, fermes, pannes et saisies invalides');
